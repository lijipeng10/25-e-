#ifndef MPU6050_H
#define MPU6050_H

#include <stdint.h>

/* ============================================================================
 *  mpu6050.h —— MPU6050 陀螺仪(只用 Z 轴积分求航向角)
 * ----------------------------------------------------------------------------
 *  约定: mpu6050_get_yaw_x10() 返回航向角, 单位 0.1°, 范围 -1800 ~ +1800。
 *        必须在"固定周期"里调用 mpu6050_update() 做积分(建议 5ms, 放定时器
 *        中断里最稳), 否则 dt 不准 -> 航向漂移。
 *  说明: 小车在地面近似水平, 单靠陀螺 Z 积分够用; 长时间漂移由循迹 PID 兜底。
 *        如需更稳可后接互补滤波(加速度计校正俯仰/横滚)。
 * ==========================================================================*/

void    mpu6050_init(void);          /* 初始化 I2C + 配置量程/滤波 + 零偏标定
                                      * ★ 调用前车必须【静止】, 而且标定要 ~400ms */
void    mpu6050_update(void);        /* 建议 5ms 周期调用: 读陀螺 + 积分航向
                                      * ★ 10ms 分频【由 empty.c 的 main 循环统一做】,
                                      *   和 line_follow_step() 共用同一拍, 所以这里
                                      *   不再提供 mpu6050_poll() —— 两处分频会各走各的 */
int32_t mpu6050_get_yaw_x10(void);   /* 航向角(0.1°), 积分值, 久了会漂 */
void    mpu6050_zero_yaw(void);      /* 把当前航向清零(上电/摆正时调用) */

/* ★ 瞬时 Z 轴角速度, 单位 0.1 度/秒。
 * ★ 符号约定【已实测确认, 不要凭猜改】: 车头往【左】转 -> 读数为【正】。
 *   (2026/09/14 手拿住车、把车头往左转, 屏幕上 R: 显示为正)
 *   之前这里写的是"右转为正", 是【没量之前猜的, 写反了】, 已更正。
 * 和航向角的区别: 航向角是"朝哪", 角速度是"正以多快的速度在转"。
 * 循迹的阻尼项要的是【角速度】—— 它不漂、而且连续(不像数字量传感器的
 * 误差是一跳一跳的台阶), 所以能提供干净的微分作用, 专治左右摆尾。 */
int16_t mpu6050_get_rate_x10(void);

/* ★ 6 轴原始值, 存的是【没换算的 LSB】, 只给屏显看传感器通不通。
 *   raw[0..2] = AX AY AZ (加速度), raw[3..5] = GX GY GZ (角速度)。
 *   静止水平放置的合理值: AZ 约 +16000(±2g 量程 = 16384 LSB/g),
 *   AX/AY 在 0 附近; GX/GY/GZ 在 0 附近小幅抖动(几百以内)。
 *   调用前必须先 mpu6050_update(), 否则拿到的是上一次的值。
 *   ★ 这里返回的是【8 点指数平均后】的值, 专门为了屏上好读;
 *     需要瞬时值的场合(比如阻尼项)用 mpu6050_get_rate_x10()。 */
void    mpu6050_get_raw(int16_t *raw);

/* ★★ 临时诊断接口, 查完就删 ★★
 *   st[0] = 成功更新次数/累计, st[1] = 读失败次数, st[2] = 连读两次对不上的次数
 *   cfg[0..2] = init 时回读的 0x1A / 0x1B / 0x1C, 期望 3 / 8 / 0
 * 判读: st[1] 或 st[2] 不为 0 -> 是 I2C 读坏了, 不是传感器噪声。 */
void    mpu6050_get_diag(uint32_t st[3], uint8_t cfg[3]);

/* 探测传感器在不在, 同时确定它的 I2C 从机地址。
 *   返回 0        = 没找到
 *   返回 0x68/0x69 = 找到了, 这就是要用的地址(内部已经设好, 后续调用不用管)
 * 两个地址都试, 因为很多模块的 AD0 是悬空/拉高的, 地址其实是 0x69。
 * ★ 传感器可能没接时, 必须先 ping, 不能直接调 mpu6050_init() ——
 *   init 里的零偏标定失败会累计等十几秒, 看起来像死机。 */
uint8_t mpu6050_ping(void);

#endif /* MPU6050_H */
