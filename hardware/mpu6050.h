#ifndef MPU6050_H
#define MPU6050_H

#include <stdint.h>

/* ============================================================================
 *  mpu6050.h —— MPU6050 陀螺仪(只用 Z 轴积分求航向角)
 * ----------------------------------------------------------------------------
 *  约定: mpu6050_get_yaw_x10() 返回航向角, 单位 0.1°, 范围 -1800 ~ +1800。
 *        必须在"固定周期"里调用 mpu6050_update() 做积分(建议 5ms, 放定时器
 *        中断里最稳), 否则 dt 不准 -> 航向漂移。
 *  说明: 小车在地面近似水平, 单靠陀螺 Z 积分够用; 长时间漂移由循迹 PID 兜底。
 *        如需更稳可后接互补滤波(加速度计校正俯仰/横滚)。
 * ==========================================================================*/

void    mpu6050_init(void);          /* 初始化 I2C + 配置量程/滤波 */
void    mpu6050_update(void);        /* 建议 5ms 周期调用: 读陀螺 + 积分航向 */
int32_t mpu6050_get_yaw_x10(void);   /* 航向角(0.1°) */
void    mpu6050_zero_yaw(void);      /* 把当前航向清零(上电/摆正时调用) */

#endif /* MPU6050_H */
