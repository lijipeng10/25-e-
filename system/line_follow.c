/* 8 路灰度传感器的权重: 最左 -7 ... 最右 +7
 * 用它算线的"重心"在哪儿: 重心偏负 = 线在左边; 偏正 = 线在右边。 */
static const int8_t LF_WEIGHT[GRAYSCALE_SENSOR_CHANNELS] = {
    -7, -5, -3, -1, +1, +3, +5, +7
};

static Pid     s_pid;               /* 转向 PID */
static uint8_t s_running;           /* 1 = 正在循迹 */
static uint8_t s_bits;              /* 最近一次灰度位图(1 = 压线, 已按 LF_LINE_LEVEL 判断) */
static uint16_t s_raw[GRAYSCALE_SENSOR_CHANNELS];  /* 最近一次灰度的原始值(0/1) */
static int16_t s_error;             /* 最近一次偏差 -100~+100 */
static int16_t s_psi_ref;           /* 外环算出的目标航向(0.1度, 左转为正), 调试用 */
static uint8_t s_left_duty;         /* 最近一次左轮占空比(调试用) */
static uint8_t s_right_duty;        /* 最近一次右轮占空比(调试用) */
static int8_t  s_last_dir;          /* 瞬时"上次往哪边拐"(只在丢线那几十毫秒用) */
static uint16_t s_lost_ms;          /* 已经连续丢线多久(ms) */

/* ★ 误差记录器: 记录【本次运行】期间 error 的最小/最大值。
 *
 * 为什么需要它: 现在调参只看 OLED, 但车在跑的时候根本没法盯屏幕,
 * 而判断"摇摆"到底是超调还是别的, 恰恰要看误差摆幅有多大。
 * 所以把一次运行里 error 到过的最小值和最大值记下来, 停下车再看屏幕:
 *      Emin/Emax 都在 ±30 以内 -> 控制稳, 车基本贴着线
 *      Emin/Emax 到 ±70 以上   -> 车已经甩到线的边上去了, 修正太晚/太弱
 *      正负都很大且对称        -> 典型的来回超调(画龙), 该降 KP
 * 每次按 KEY1 启动循迹时清零, 所以它反映的是"这一次跑得怎么样"。 */
static int16_t  s_e_min;            /* 本次运行 error 的最小值 */
static int16_t  s_e_max;            /* 本次运行 error 的最大值 */

/* ★ 摆动计数器: 数 error 的符号翻了几次(来回摆了几次)。
 *
 * 为什么要它: 光看"最大/最小"只知道摆【多厉害】, 不知道摆【多快】。
 * 而这两种毛病的改法是相反的:
 *      摆得快(次数多、幅度小) -> 控制器反应太灵敏 -> 降 LF_POS_KP(或 LF_HEAD_KP)
 *      摆得慢(次数少、幅度大) -> 控制器太弱 -> 加 LF_POS_KP
 * 所以必须把"次数"也量出来。
 *
 * 计数条件: error 从 <=-14 翻到 >=+14(或反过来)才算一次 ——
 * 必须越过一整档(14), 这样才不会被 0 附近的小抖动刷成天文数字。 */
static int16_t  s_prev_err;         /* 上一拍的误差 */
static uint16_t s_e_flips;          /* 本次运行 error 符号翻转次数 */

/* ★★ 方向证据 —— 决定弯道往哪边转 ★★
 *
 * 踩过的坑: 原来直接用 s_last_dir 定转向方向, 结果到弯道"算不出往哪边转"。
 * 原因: s_last_dir 是【瞬时值】, 而直线上误差本来就在 ±14 之间抖, 每次小修正
 *       都会把它在 +1 / -1 之间来回翻。到丢线那一刻, 它记下的只是最后一次
 *       无意义的抖动, 跟弯的方向完全无关 —— 等于在猜。
 *
 * 改法: 累积"方向证据"。只在看到线的时候更新, 而且用泄漏积分:
 *          s_dir_ev = s_dir_ev * 7/8 + error
 *   效果: 直线上那种 ±14 的正负抖动会互相抵消(证据一直贴着 0 附近);
 *         而弯道口那条【横扫过来的横向线】会连续好几拍给出同号的大偏差,
 *         证据就会稳稳地积累到一边。这样判断的才是"趋势", 不是"噪声"。
 * 限幅是为了让方向证据能及时被新情况翻转, 不至于被历史拖住。 */
static int32_t  s_dir_ev;           /* 方向证据: 正 = 线一直在偏右, 负 = 偏左 */

static uint8_t  s_pivoting;         /* 1 = 正在原地转向(弯道模式) */
static int8_t   s_pivot_dir;        /* 本次原地转向往哪边(开始时定下, 中途不变) */
static uint8_t  s_pivot_try;        /* 0 = 第一遍(按证据方向), 1 = 第二遍(反方向) */
static uint16_t s_pivot_ms;         /* 当前这一遍已经转了多久(ms) */
static uint16_t s_corner_ms;        /* |error| 已经连续超阈值多久(ms), 急弯判据用 */

/* ============================================================================
 *  内部函数
 * ==========================================================================*/

/* ---------------------------------------------------------------------------
 *  读 8 路灰度, 返回位图: bit0 = 最左那路, 1 = 压线
 * -------------------------------------------------------------------------*/
static uint8_t lf_read_bits(void)
{
    uint16_t g[GRAYSCALE_SENSOR_CHANNELS];
    uint8_t  i;
    uint8_t  bits = 0U;

    Grayscale_Sensor_Read_All(g);       /* 这个函数内部有 ~400us 延时, 别调太快 */

    for (i = 0U; i < GRAYSCALE_SENSOR_CHANNELS; i++) {
        s_raw[i] = g[i];                    /* 原样存一份给调试显示用 */

        if (g[i] == LF_LINE_LEVEL) {
            bits |= (uint8_t)(1U << i);     /* 第 i 路压线了, 把第 i 位置 1 */
        }
    }
    return bits;
}

/* ---------------------------------------------------------------------------
 *  由位图算偏差: 返回 -100(线在最左) ~ 0(正中间) ~ +100(线在最右)
 *  一个通道都没压线(丢线)时, 通过 *on_line 返回 0
 * -------------------------------------------------------------------------*/
static int16_t lf_calc_error(uint8_t bits, uint8_t *on_line)
{
    int32_t sum = 0;                    /* 权重累加 */
    uint8_t cnt = 0U;                   /* 压线的通道数 */
    uint8_t i;

    for (i = 0U; i < GRAYSCALE_SENSOR_CHANNELS; i++) {
        if ((bits & (uint8_t)(1U << i)) != 0U) {
            sum += (int32_t)LF_WEIGHT[i];
            cnt++;
        }
    }

    if (cnt == 0U) {                    /* 丢线 */
        *on_line = 0U;
        return 0;
    }
    *on_line = 1U;

    /* 先把权重取平均(得到 -7~+7), 再放大到 -100~+100。
     * 写法 sum*100/(cnt*7) 是为了先乘后除, 避免整数除法丢精度。 */
    return (int16_t)((sum * 100) / ((int32_t)cnt * 7));
}

/* ---------------------------------------------------------------------------
 *  让一个轮子转
 *      id      : 1 = A路, 2 = B路
 *      fwd_dir : 该轮"前进"对应的方向值(1 或 2)
 *      cmd     : 带符号的占空比
 *                  > 0  前进, 大小 = 占空比
 *                  < 0  后退(只有"原地转向"会用到)
 *                  = 0  停
 *
 *  ★ 注意: 负数是【反转】, 不是停! 所以循迹的差速输出在传进来之前
 *    必须先自己夹到 0 以上(见 line_follow_step 里的限幅), 否则大偏差时
 *    慢的那一侧会突然倒转, 车会甩出去。
 * -------------------------------------------------------------------------*/
static void lf_set_wheel(uint8_t id, uint8_t fwd_dir, int32_t cmd)
{
    uint8_t dir;

    if (cmd == 0) {
        motor_set_direction(id, 0U);            /* 方向脚清零 = 停 */
        motor_set_duty(id, 0U);
        return;
    }

    if (cmd > 0) {
        dir = fwd_dir;                          /* 前进 */
    } else {
        /* 后退。motor.c 里方向只有 1 / 2 两个值, 取"另一个"就是反方向。
         * (A路: 1 = 正转, 2 = 反转; B路: 2 = 正转, 1 = 反转)
         * 如果以后给某一路加了别的方向定义, 这里要跟着改。 */
        dir = (uint8_t)((fwd_dir == 1U) ? 2U : 1U);
        cmd = -cmd;
    }

    /* ★ 最高速度的硬顶。所有往电机发的值都从这里过, 所以改了这里,
     *   不管上面怎么算都不可能超速 —— 这是最后一道保险。 */
    if (cmd > LF_MAX_DUTY) { cmd = LF_MAX_DUTY; }

    motor_set_direction(id, dir);
    motor_set_duty(id, (uint16_t)cmd);
}

/* ---------------------------------------------------------------------------
 *  两个轮子一起停
 *  注意: 这里不用 motor_stop(), 因为 motor_stop() 内部是"两路都停",
 *        我们分开写更清楚, 也方便以后单独控制某一个轮子。
 * -------------------------------------------------------------------------*/
static void lf_stop_wheels(void)
{
    lf_set_wheel(LF_LEFT_ID,  LF_LEFT_FWD_DIR,  0);
    lf_set_wheel(LF_RIGHT_ID, LF_RIGHT_FWD_DIR, 0);
    s_left_duty  = 0U;
    s_right_duty = 0U;
}

/* ---------------------------------------------------------------------------
 *  原地转向: 两个轮子一正一反, 车绕自己中心转
 *      dir > 0 : 往右转(左轮前进, 右轮后退)
 *      dir < 0 : 往左转
 * -------------------------------------------------------------------------*/
static void lf_pivot(int8_t dir)
{
    int32_t d = (int32_t)LF_PIVOT_DUTY;

    if (dir > 0) {
        lf_set_wheel(LF_LEFT_ID,  LF_LEFT_FWD_DIR,   d);    /* 左轮前进 */
        lf_set_wheel(LF_RIGHT_ID, LF_RIGHT_FWD_DIR, -d);    /* 右轮后退 */
    } else {
        lf_set_wheel(LF_LEFT_ID,  LF_LEFT_FWD_DIR,  -d);    /* 左轮后退 */
        lf_set_wheel(LF_RIGHT_ID, LF_RIGHT_FWD_DIR,  d);    /* 右轮前进 */
    }

    s_left_duty  = (uint8_t)d;
    s_right_duty = (uint8_t)d;
}

/* ============================================================================
 *  对外接口
 * ==========================================================================*/

void line_follow_init(void)
{
    /* 初始化【内环(航向环)】PID:
     *   pid_init(&pid, kp, ki, kd, div, 积分限幅, 输出限幅, 死区, 最小dt)
     * ★ div = 100: 输出正好是 LF_HEAD_KP * e_psi / 100, 和上面的算式一致。
     * ★ 输出限幅 = LF_MAX_STEER: 内环直接出转向量, 限幅就该是它。
     * ★ 死区给 0: 航向是连续量, 不需要死区。
     *   (原来的 LF_DEADBAND 是给"量化误差"用的, 现在它作用在外环上, 见那里的说明) */
    pid_init(&s_pid, LF_HEAD_KP, LF_HEAD_KI, LF_HEAD_KD, 100,
             0, LF_MAX_STEER, 0, LF_STEP_MS);

    s_running    = 0U;
    s_bits       = 0U;
    s_error      = 0;
    s_left_duty  = 0U;
    s_right_duty = 0U;
    s_last_dir   = 0;
    s_lost_ms    = 0U;
    s_dir_ev     = 0;
    s_pivoting   = 0U;
    s_pivot_dir  = +1;
    s_pivot_try  = 0U;
    s_pivot_ms   = 0U;
    s_corner_ms  = 0U;
    s_e_min      = 0;
    s_e_max      = 0;
    s_prev_err   = 0;
    s_e_flips    = 0U;
}

void line_follow_start(void)
{
    pid_reset(&s_pid);          /* 清掉上次的积分/微分残留, 不然起步会猛地一拐 */

    /* ★★ 航向零点(第一个清零点) ★★
     *
     * 外环给的是【相对航向】("相对起步那一刻的车头方向"要转多少度), 内环拿它
     * 和航向角比。航向角是陀螺积分出来的, 不清零的话它带着上电以来的累积值,
     * 内环一上来就会拼命往那个旧角度追。
     *
     * ★ 所以按 KEY1 启动的那一瞬间, 车【必须摆正、对着线的方向】——
     *   这一瞬间的车头方向就成了整段路的"0 度"。起步时歪着, 车就会一路上
     *   带着这个初始偏差跑。
     *
     * 另一个清零点在弯道原地转向结束时(那里车头刚对准新线, 同样该是 0 度)。
     * 两处一配合, 陀螺仪的缓慢漂移也被顺带清掉, 根本来不及积累。 */
    mpu6050_zero_yaw();

    s_lost_ms   = 0U;
    s_last_dir  = 0;
    s_dir_ev    = 0;        /* 方向证据也清空, 从头攒 */
    s_pivoting  = 0U;
    s_pivot_dir = +1;
    s_pivot_try = 0U;
    s_pivot_ms  = 0U;
    s_corner_ms = 0U;
    s_e_min     = 0;        /* 误差记录器清零, 只记这一次运行 */
    s_e_max     = 0;
    s_prev_err  = 0;
    s_e_flips   = 0U;
    s_running   = 1U;
}

void line_follow_stop(void)
{
    s_running  = 0U;
    s_pivoting = 0U;            /* 顺手退出弯道转向状态 */
    lf_stop_wheels();           /* 立刻把两个轮子关掉 */
}

uint8_t line_follow_is_running(void)
{
    return s_running;
}

uint8_t line_follow_is_pivoting(void)
{
    return s_pivoting;
}

/* ---------------------------------------------------------------------------
 *  判断"该往哪边转": 优先用【方向证据】, 不够再退回瞬时方向, 再不够默认往右。
 *
 *  ★ 为什么不能直接用瞬时方向 s_last_dir: 它是"线上最后一次小抖动的方向"。
 *    直线循迹时误差在 ±14 之间摆, 每次小修正都会把它翻来翻去,
 *    到弯道那一刻它跟弯的方向【毫无关系】—— 用它就会拐反方向, 直接冲过头。
 *    这个坑踩过两次(先是原地转向, 后是丢线窗口), 所以统一收在这里。
 * -------------------------------------------------------------------------*/
static int8_t lf_best_dir(void)
{
    if (s_dir_ev > 0)    { return +1; }
    if (s_dir_ev < 0)    { return -1; }
    if (s_last_dir != 0) { return s_last_dir; }
    return +1;                          /* 什么线索都没有, 默认往右找 */
}

/* ---------------------------------------------------------------------------
 *  进入"原地转向"状态: 定好方向、清零计时、并且【立刻把轮子停住】。
 *  停住这一步很重要 —— 就是为了不冲过弯节点。
 * -------------------------------------------------------------------------*/
static void lf_enter_pivot(void)
{
    s_pivot_dir = lf_best_dir();
    s_pivoting  = 1U;
    s_pivot_try = 0U;
    s_pivot_ms  = 0U;
    s_corner_ms = 0U;
    lf_stop_wheels();
}

/* ---------------------------------------------------------------------------
 *  控制步进: 每 10ms 调一次
 * -------------------------------------------------------------------------*/
void line_follow_step(void)
{
    uint8_t  on_line;
    int16_t  error;
    int32_t  steer;
    int32_t  left_cmd, right_cmd;
    int32_t  base;
    int32_t  psi_ref;           /* 外环输出: 目标航向(0.1度, 左转为正) */
    int32_t  e_psi;             /* 内环输入: 目标航向 - 实际航向 */
    int32_t  damp;              /* 陀螺仪阻尼量 */


    /* ---------------- 第 1 步: 读灰度, 算偏差 ----------------
     * ★ 注意: 这一步无论"循迹跑不跑"都必须做!
     *   因为屏幕和串口显示的调试数据就是这里读出来的。
     *   如果停着就不读, 就没法在不启动电机的情况下标定传感器了
     *   (之前就是这里写错顺序, 导致没按 KEY1 时 S 一直是 00000000)。 */
    s_bits  = lf_read_bits();
    error   = lf_calc_error(s_bits, &on_line);
    s_error = error;

    /* 没在循迹: 数据照读照更新, 但不驱动电机 */
    if (s_running == 0U) {
        return;
    }

    /* 记录本次运行的误差摆幅(见 s_e_min / s_e_max 的说明) */
    if (error < s_e_min) { s_e_min = error; }
    if (error > s_e_max) { s_e_max = error; }

    /* 数摆动次数(见 s_e_flips 的说明): 必须越过一整档 14 才算翻了一次 */
    if (((error >= 14) && (s_prev_err <= -14)) ||
        ((error <= -14) && (s_prev_err >= 14))) {
        s_e_flips++;
    }
    s_prev_err = error;

    /* ================================================================
     *  状态 A: 正在原地转向(弯道模式)
     * ============================================================== */
    if (s_pivoting != 0U)
    {
        s_pivot_ms += LF_STEP_MS;

        /* 线重新出现在【中间附近】= 车头已经对准新方向 -> 停转, 回去循迹。
         * 为什么要求"在中间": 转的过程中线会从一边扫到另一边, 如果一看到线
         * 就停, 车头还是歪的。等它扫到中间, 才说明车头正对着新方向。 */
        if ((on_line != 0U) && (error <= LF_PIVOT_OK) && (error >= -LF_PIVOT_OK)) {
            pid_reset(&s_pid);      /* 清掉转向过程中残留的量, 免得接着猛拐一下 */

            /* ★ 航向零点(第二个清零点, 见文件上面"四、航向零点"):
             *   能走到这里就说明线已经在【中间附近】了 —— 车头刚刚对准
             *   新的这段线, 那么"现在这个方向"就该是新的 0 度。
             *   原地转向会让航向角甩出去一大截, 不在这里清零, 转完弯内环
             *   会拼命想把车头扭回【转弯前】的航向 —— 那就直接冲出去了。 */
            mpu6050_zero_yaw();

            s_lost_ms  = 0U;
            s_pivoting = 0U;
            s_dir_ev   = 0;         /* 这一弯的证据用完了, 清空, 下一弯重新攒 */
            /* 这里【不 return】: 直接落下去按正常循迹走一拍, 衔接更顺 */
        }
        else {
            /* ★ 兜底: 一个方向找够了还没扫到线, 就【掉头往反方向找】。
             *   这样不管方向证据猜得对不对, 两个方向都扫一遍总能扫到,
             *   车就不会一直在那儿原地转圈了。 */
            if (s_pivot_ms >= LF_PIVOT_TRY_MS) {
                if (s_pivot_try == 0U) {
                    s_pivot_try = 1U;
                    s_pivot_ms  = 0U;
                    s_pivot_dir = (int8_t)(-s_pivot_dir);   /* 掉头 */
                } else {
                    /* 两边都扫遍了还是没有线 -> 车多半已经掉出赛道, 停车 */
                    line_follow_stop();
                    return;
                }
            }

            lf_pivot(s_pivot_dir);  /* 还没对准, 继续原地转 */
            return;
        }
    }

    /* ================================================================
     *  状态 B: 正常循迹
     * ============================================================== */

    /* ---------------- 第 2 步: 算转向量 steer ---------------- */
    if (on_line != 0U) {
        /* 看到线了: 正常循迹 */
        s_lost_ms = 0U;

        /* 累积"往哪边偏"的方向证据(见 s_dir_ev 的说明)。
         * 只在这里更新 —— 丢线时不更新, 这样弯道口攒下来的证据能保住,
         * 供原地转向决定方向用。 */
        s_dir_ev = (s_dir_ev * 7) / 8 + (int32_t)error;
        if (s_dir_ev >  400) { s_dir_ev =  400; }
        if (s_dir_ev < -400) { s_dir_ev = -400; }

        /* ★ 急弯提前判定(见 LF_CORNER_ERR 的说明):
         *   线已经甩到传感器边上并且持续了一小会儿 -> 不等丢线, 立刻停车转向。
         *   这是"过弯冲过头"的关键补丁。 */
        if ((error >= LF_CORNER_ERR) || (error <= -LF_CORNER_ERR)) {
            s_corner_ms += LF_STEP_MS;
            if (s_corner_ms >= LF_CORNER_MS) {
                lf_enter_pivot();
                return;
            }
        } else {
            s_corner_ms = 0U;
        }

        base = LF_BASE_DUTY;

        /* ================= 外环: 位置误差 -> 目标航向 =================
         * 乘 LF_STEER_SIGN 是为了方便一键反方向(和单环时代的用法一致)。
         * ★ 最外层那个负号的原因见文件上面"三、符号是怎么定的"。
         * ★ 死区作用在外环上: |error| 不超过 LF_DEADBAND 时目标航向给 0,
         *   也就是"不修正"。默认 LF_DEADBAND = 0, 等于不生效。 */
        psi_ref = -((int32_t)LF_POS_KP * (int32_t)error * LF_STEER_SIGN);
        if ((error <= LF_DEADBAND) && (error >= -LF_DEADBAND)) {
            psi_ref = 0;
        }
        if (psi_ref >  LF_PSI_MAX) { psi_ref =  LF_PSI_MAX; }
        if (psi_ref < -LF_PSI_MAX) { psi_ref = -LF_PSI_MAX; }
        s_psi_ref = (int16_t)psi_ref;

        /* ================= 内环: 让车头去追目标航向 =================
         *   e_psi > 0 = "还要往左转", 而往左转要给【负】的 steer -> 取负号。
         * ★ 内环只吃航向差, 不吃位置误差 —— 位置信息已经在 psi_ref 里了。 */
        e_psi = psi_ref - mpu6050_get_yaw_x10();
        steer = -pid_update(&s_pid, e_psi, LF_STEP_MS);

        /* ★ 先记下"这一次想往哪边拐"(丢线时要用), 必须取【加阻尼之前】的符号。
         *   阻尼在急弯上可能大到把 steer 压成反号(见 LF_GYRO_KD 的说明),
         *   那样记下来的方向就是反的 -> 丢线时把车往错的方向带。 */
        if (steer > 0)      { s_last_dir = +1; }
        else if (steer < 0) { s_last_dir = -1; }

        /* ★ 加上陀螺仪阻尼(见 LF_GYRO_KD 的说明)。
         *   角速度(0.1度/秒) -> 阻尼量: 除以 1000 正好是"度/秒 / 100"的量纲。
         *   传感器没接时 rate 恒为 0, 这一项自动失效。 */
        damp = (int32_t)LF_GYRO_KD * (int32_t)mpu6050_get_rate_x10() / 1000;
        steer += damp;
    }
    else {
        /* 丢线了: 一个通道都没看到黑线 */
        s_corner_ms = 0U;
        s_lost_ms  += LF_STEP_MS;

        /* 兜底判据: 连续丢线够久 -> 判定到弯节点, 停车转向。
         * (正常急弯会先被上面的 LF_CORNER_ERR 抓住, 走到这里的机会不多) */
        if (s_lost_ms >= LF_PIVOT_TRIGGER_MS) {
            lf_enter_pivot();
            return;
        }

        /* 还没到判定时间: 继续一边找线一边降速,
         * 好让线上一个小缺口能直接开过去, 不误触发停车。
         *
         * ★ 方向必须用 lf_best_dir()(优先方向证据), 不能再用瞬时方向 ——
         *   之前这里用的是 s_last_dir, 那是线上最后一次小抖动的方向,
         *   跟弯的方向没关系, 会拐反 -> 直接冲过弯。 */
        base  = LF_LOST_DUTY;
        steer = (int32_t)lf_best_dir() * LF_MAX_STEER;
    }

    /* ---------------------------------------------------------------
     *  小技巧: 修正量到底往哪边掰, 取决于"线偏的方向"和"轮子快慢"的对应关系。
     *  我们这里的约定是:
     *      error < 0 (线在左边)  ->  steer < 0  ->  左轮变慢、右轮变快  ->  车往左拐  ✓
     *      error > 0 (线在右边)  ->  steer > 0  ->  左轮变快、右轮变慢  ->  车往右拐  ✓
     *  如果实测反了(越偏越远), 把上面的 LF_STEER_SIGN 改成 -1 即可。
     * --------------------------------------------------------------- */

    /* 记住这次拐的方向(丢线时要用)。
     * ★ 看线时的那一次已经在上面【加阻尼之前】记过了, 不能在这里再记一遍 ——
     *   这里的 steer 已经带上阻尼, 急弯上可能是反的。
     *   这里只管丢线分支: 那时 steer = lf_best_dir()*LF_MAX_STEER, 符号本来就清楚。 */
    if (on_line == 0U) {
        if (steer > 0)      { s_last_dir = +1; }
        else if (steer < 0) { s_last_dir = -1; }
    }

    /* ---------------- 第 3 步: 差速输出 ---------------- */
    left_cmd  = base + steer;       /* 线偏左时 steer<0 -> 左轮慢 */
    right_cmd = base - steer;       /*                    右轮快 */

    /* 再补上"两个电机本身不一样"这一步。见 LF_TRIM 的说明。
     * 一加一减, 平均速度不变, 只调左右出力的分配。 */
    left_cmd  -= LF_TRIM;
    right_cmd += LF_TRIM;

    /* 限幅: 两边都不许倒转, 慢的一侧最多降到 0。
     * (最基础版本先这么保守, 稳住不跑飞比较重要) */
    if (left_cmd  < 0) { left_cmd  = 0; }
    if (right_cmd < 0) { right_cmd = 0; }

    lf_set_wheel(LF_LEFT_ID,  LF_LEFT_FWD_DIR,  left_cmd);
    lf_set_wheel(LF_RIGHT_ID, LF_RIGHT_FWD_DIR, right_cmd);

    s_left_duty  = (uint8_t)left_cmd;
    s_right_duty = (uint8_t)right_cmd;
}

