#define LF_STEER_SIGN       (+1)

/* ============================================================================
 *  控制器: 双环(航向环)
 * ----------------------------------------------------------------------------
 * 【双环, 各管一件事】
 *   外环(慢): 位置误差 error -> 目标航向 psi_ref。只为回答"该朝哪"
 *   内环(快): 航向差 e_psi -> 转向量 steer。只为回答"该转多快"
 *   ★ 阻尼挂在内环上: 车按 psi_ref 转弯时 e_psi 不会变小, 所以阻尼
 *     压不灭"想转弯", 只能压住"转过头/在晃" —— 单环做不到这一点。
 *
 * 【算式】
 *   psi_ref = -LF_POS_KP * error              [0.1度, 左转为正]
 *   e_psi   = psi_ref - mpu6050_get_yaw_x10()
 *   steer   = -(LF_HEAD_KP * e_psi)/100       [mm/s]
 *   steer  += LF_GYRO_KD * 角速度 / 1000
 *
 * 【符号(别凭猜改)】航向【左转为正】, 而 steer>0 是【右转】, 两者反号。
 *
 * 【航向零点】外环控制的是"相对起步车头"的角度, 所以两个时刻必须清零:
 *   按KEY1启动时(车要摆正)、每次原地转向结束(车头刚对准新线)。
 *
 * 【退回单环】git revert 即可。★ 不能把 LF_POS_KP 设成 0 来"关掉":
 *   那样 psi_ref 恒为 0, 内环会死保起步航向, 车直着冲出去。
 *
 * 【为什么原来的 LF_KD = 12 不能要】
 * 8 路是"数字量"传感器, 算出来的 error 是【一档一档跳】的, 只可能是:
 *      0, ±14, ±28, ±43, ±57, ±71, ±85, ±100
 * (只有一路压线时 error = 权重*100/7, 权重是 1/3/5/7, 所以最小跳变 = 14)
 *
 * 于是 error 每跳一档(变化量 14):
 *      比例项 P = 0.15 * 14 = 2.1
 *      微分项 D = 0.1 * 12 * 14 = 16.8                   <-- 是 P 的【8 倍】!
 *
 * 后果分三拍看(steer 直接加在左右轮上):
 *      第1拍  error 0 -> +14 : steer = +2.1 + 16.8 = +19  (该轻修, 结果猛打)
 *      第2拍  error 还是 +14 : steer = +2.1 +  0   = +2   (又突然不管了)
 *      第3拍  error +14 -> 0 : steer =  0   - 16.8 = -17  (★ 回到中线却反着打方向!)
 * 第 3 拍是最要命的: 车已经回到线正中间了, 闭环反而把车往反方向推,
 * 于是 回中线 -> 被反推出去 -> 再猛拉回来 -> 画龙。
 *
 * 【结论 —— 这条结论现在用在【内环】上】
 * 外环的 psi_ref 是拿量化的 error 直接乘出来的, 所以那些台阶会【原样传进】
 * 内环的 e_psi。对这种"一档一档跳"的信号, 微分项要么不用, 要么取很小 ——
 * 它放大的其实是量化台阶, 不是真实趋势。
 * 让 D 不超过 P 的一半:
 *      e_psi 一跳 = LF_POS_KP * 14 = 42
 *      0.1 * LF_HEAD_KD * 42  <=  (LF_HEAD_KP * 42 / 100) / 2
 *      代入 LF_HEAD_KP = 5 :  4.2 * LF_HEAD_KD <= 1.05  ->  LF_HEAD_KD <= 0.25
 * 也就是说这一档上 D 项【根本不该开】, 只能取 0。
 * ★ 想要阻尼请用 LF_GYRO_KD(陀螺仪直接给角速度, 连续干净, 不受量化影响),
 *   不要回头去加 LF_HEAD_KD。 */
/* ★★★ 双环的两个增益 —— 调参主要就是调这两个 ★★★
 *
 * 【外环 LF_POS_KP】位置误差 -> 目标航向。单位: 0.1 度 / 每 1 格误差
 *      psi_ref = -LF_POS_KP * error
 *
 *   它回答: "线偏了这么多, 车头该朝哪个方向去追?"
 *   误差 ±14 -> ±2.8度   ±28 -> ±5.6度   ±71 -> ±14.2度   ±100 -> ±20度(满)
 *   ★ 调大 = 回正积极但容易冲过头; 调小 = 温和但贴不上线
 *   ★★ 天花板: psi_ref 最大只能是 LF_POS_KP*10 度(误差卡在±100)。
 *      所以要转 70 度以上的弯【不是外环的活, 是原地转向的活】。
 *      降它同时治"直道摆"和"弯道转太猛"。
 *
 * 【内环 LF_HEAD_KP】航向差 -> 转向量。单位: 每 10 度航向差给多少占空比
 *      steer = -(LF_HEAD_KP * e_psi) / 100
 *
 *   它回答: "车头离目标航向还差这么多, 该给多大转向?"
 *   取 5 时的对照表:
 *       航向差 4.2 度 -> steer 2.1  (轻轻修)
 *       航向差 10  度 -> steer 5
 *       航向差 30  度 -> steer 15
 *       航向差 40  度 -> steer 20   (被 LF_MAX_STEER 截断)
 *
 *   ★ 调大: 车头追目标更快更"跟手", 但太大在直道上会抖
 *   ★ 调小: 外环给了目标航向, 车头却跟不上 —— 表现为"想转但转不动"
 *
 * 【和单环时代 LF_KP=15 的量级对照(便于心里有数)】
 *   单环是 steer ≈ 15*error/100 = 0.15*error。
 *   现在瞬时上约等于 外环2 * 内环5 / 100 = 0.10*error —— 比单环温和约 1/3。
 *   (双环刚上时外环给的是 3, 对应 0.15 —— 和单环同量级; 实测反馈"直线还有
 *    一点摆", 所以把外环从 3 降到 2, 顺带也把弯道的转速降下来了, 见上。)
 *
 * 【LF_PSI_MAX】目标航向限幅(0.1 度)。LF_POS_KP=2 时天花板是 20 度
 *   (error 卡在 ±100), 根本用不到它; 它是给"把 LF_POS_KP 调得很大"兜底的 ——
 *   否则 psi_ref 会变成一个荒唐的角度(比如 300 度), 让内环一直顶着饱和。 */
#define LF_POS_KP           2       /* 外环: 位置误差 -> 目标航向 */
#define LF_PSI_MAX          600     /* 目标航向限幅 ±60 度 (0.1度) */
#define LF_HEAD_KP          100     /* 内环: 每 10 度航向差给多少 mm/s。取100 -> 约 67 度/秒 */
#define LF_HEAD_KI          0       /* 内环积分: 先不用。调稳之后它可以补掉
                                       稳态航向差(转弯时阻尼造成的"追不上") */
#define LF_HEAD_KD          0       /* 内环微分: 见上面。量化台阶上只会帮倒忙,
                                       要阻尼请用 LF_GYRO_KD */

/* 双环增益的编译期检查: 这两个取 0 都不是"关掉", 而是【车会失控】。 */
#if (LF_POS_KP <= 0)
#error "LF_POS_KP 必须 > 0: 外环取 0 则 psi_ref 恒为 0, 内环会死保起步航向, 车直着冲出去"
#endif
#if (LF_HEAD_KP <= 0)
#error "LF_HEAD_KP 必须 > 0: 内环取 0 则转向量恒为 0(只剩阻尼), 车根本不会拐弯"
#endif
#if (LF_PSI_MAX <= 0)
#error "LF_PSI_MAX 必须 > 0"
#endif

/* ★★ 陀螺仪阻尼项 —— 专治【左右摆尾】 ★★
 *
 * 【为什么需要它】
 *   摆尾的本质是【欠阻尼振荡】: 车头偏过中线, 控制器按"位置误差"给修正,
 *   但等它发现"已经偏过去了"已经晚了 -> 冲过头 -> 反方向再修 -> 再冲过头。
 *
 *   理想解法是加微分项(看误差的【变化速度】, 提前点刹)。
 *   但我们试过: 8 路数字传感器的误差是【一跳 14】的台阶信号,
 *   数值微分放大的全是台阶噪声 —— LF_KD=12 那次摆得更凶就是这个原因。
 *
 *   陀螺仪直接给出【角速度】, 连续、干净、不受量化影响。
 *   对前进中的车, 传感器那一点的横向速度 ≈ 角速度 × 距离, 所以:
 *
 *        steer = KP*error − K_gyro*角速度
 *
 *   这就是一个货真价实的 PD 控制器, 而且 D 项终于是干净的了。
 *
 * 【量纲】阻尼量 = LF_GYRO_KD × 角速度(度/秒) / 100
 *   也就是: 角速度 100 度/秒 时, 阻尼量 = LF_GYRO_KD 个占空比单位。
 *   参考: 现在"修正量"是内环的输出 = LF_HEAD_KP*e_psi/100, 上限就是 LF_MAX_STEER。
 *   单环时代的位置修正项最大也只有 LF_MAX_STEER 那么多 —— 所以下面
 *   "阻尼会不会吃掉修正量"的算法在双环下照样成立(内环同样会被阻尼压制)。
 *
 * 【★ 符号: 已实测确认, 不要凭猜改 ★】
 *   实测(手拿住车, 车头往【左】转): 屏幕上 R: 显示【正】。
 *   即 mpu6050 的约定是【左转为正】—— 我原来注释写成"右转为正", 是错的。
 *   车头往左转 -> 要把车往右拉 -> steer 要为正 -> LF_GYRO_KD 取【正号】。
 *
 * 【★★ 为什么从 10 降到 6 —— 实测教训, 这是本项最大的坑 ★★】
 *   2026/09/14 赛道实测反馈: "摆正了能流畅走直; 偏了之后左右左右走(但不出线);
 *                             到拐角容易【转反】丢线"。
 *
 *   后两句其实是一对矛盾, 根子在于这一项【正比于角速度】:
 *       直道小幅摆动   40 度/秒 -> 阻尼 10*40/100  = 4   -> 压摆, 正好("有一点阻尼")
 *       急弯正常转弯  150 度/秒 -> 阻尼 10*150/100 = 15  -> ★ 正好等于修正量上限 15!
 *
 *   150 度/秒 不是夸张值 —— 本车原地转向本身就有约 150 度/秒(见 LF_PIVOT_TRY_MS)。
 *   阻尼到 15 意味着 P 项被【完全抵消】, 车在弯上根本转不动; 只要再有一点扰动
 *   让阻尼超过修正量, steer 当场【反号】—— 这正是实测看到的
 *   "到拐角就转反、然后丢线"。
 *
 *   而且在"线还在视野里"的时候, 代码里唯一能让 steer 反号的量就是这一项
 *   (修正量符号跟着 error 走, 原地转向方向跟着方向证据走, 都不会自己反)。
 *
 *   ★ 所以这一项的毛病是【本质】的: 它分不清"我在按要求转弯"和"我在乱晃",
 *     一律反对, 而且角速度越大反对得越狠 —— 恰恰在最需要转弯的时候最碍事。
 *     光调这一个数做不到两全: 调大保直道、弯道转不动; 调小保弯道、直道又摆。
 *     ★ 根治办法是给它一个【参照系】(航向环: 相对目标航向来阻尼,
 *       而不是无条件反对一切旋转) —— 那是下一步的事, 见 PROJECT.md。
 *     当前先取 6 折中:
 *       直道阻尼 40 度/秒 -> 2.4  (弱一些, 但直道本来就不会出线)
 *       急弯     150 度/秒 -> 9    (小于修正量上限 15, 弯上还转得动) ✓
 *
 * 【大小怎么调】
 *   弯道还是转反 / 转不动 -> 继续降: 6 -> 4 -> 2 -> 0(关掉)
 *   直道摆得明显了        -> 加回去: 6 -> 8 -> 10, 但要盯紧弯道
 *   传感器没接也没关系    -> 角速度恒为 0, 这一项自然失效, 不影响别的功能 */
#define LF_GYRO_KD          150     /* 阻尼: 每 1 度/秒 给多少 mm/s。150 = 和 LF_HEAD_KP 同量级 */

/* ★★ 死区: |error| 小于它就输出 0, 不做任何修正。★ 现在给 0 ★★
 *
 * 【曾经的错误想法】最初加它是想压掉数字量传感器的量化抖动:
 *   误差最小跳变是 14, 于是"只差一路"时车在 +2/0/-2 之间来回跳 -> 以为会摆。
 *   当时取 15, 想把这"一档"整个压掉。
 *
 * 【实测证明这是错的】压掉之后摆得更厉害, 原因:
 *   死区把 ±14 变成 0, 于是从"完全不管"到"±28 时的猛打"之间【没有过渡】,
 *   车在线中间自由漂移 -> 到 2 路误差被猛踢 -> 冲过头 -> 反号 -> 再踢回来。
 *   死区越大, 这个台阶越高, 摆得越凶。
 *
 * 【正确做法】不要用死区, 靠外环增益 LF_POS_KP 把曲线做平缓:
 *   误差 ±14 时给一个很小的修正(速度差 2), 就足以把量化抖动压住,
 *   同时又让车"一路都有人在管", 不会自由漂移。
 *
 * ★ 所以这里给 0: 误差 0 时目标航向本来就是 0, 死区分支根本不会被触发。
 *   如果以后要加回来, 一定同时把 LF_POS_KP 调小, 否则台阶又会出来。
 * ★ 双环之后它作用在【外环】上(见 line_follow_step 里外环那一段)。 */
#define LF_DEADBAND         0

/* ★★ 转向量上限 —— 这个值直接决定"转得过弯还是冲过弯" ★★
 *
 * 差速输出是:
 *      慢的一侧 = LF_BASE_DUTY - steer
 *      快的一侧 = LF_BASE_DUTY + steer
 *
 * 【转弯力度 = 快的一侧 - 慢的一侧】, 也就是看这个差有多大。
 * 而要让这个差达到最大(= LF_MAX_DUTY, 也就是 20), 必须让【慢的一侧降到 0】。
 * 于是得到唯一正确的约束:
 *
 *      LF_MAX_STEER >= LF_BASE_DUTY
 *
 * 代入数字看(基础速度 18):
 *      LF_MAX_STEER =  6 -> 慢轮 12, 快轮 20 -> 速度差 8    <- 转不过弯
 *      LF_MAX_STEER = 18 -> 慢轮 0,  快轮 20 -> 速度差 20   <- 正确
 *
 * 为什么之前会冲过弯道: 慢的一侧最低只能降到 LF_BASE_DUTY - LF_MAX_STEER,
 * 只要它降不到 0, 速度差就上不去, 车就转不过来。
 *
 * 注意 LF_MAX_STEER 不需要大于 LF_BASE_DUTY —— 超出的部分会被 lf_set_wheel()
 * 的硬顶截掉, 白给。取相等正好。 */
#define LF_MAX_STEER        250     /* 转向量上限。必须 >= LF_BASE_SPEED(慢轮要能降到0), 取等正好 */

/* 编译期检查: 参数配错了直接编译报错, 不要等到跑车才发现。 */
#if (LF_LOST_SPEED > LF_BASE_SPEED)
#error "LF_LOST_SPEED 不该大于 LF_BASE_SPEED: 丢线时是【降速】找线"
#endif
#if (LF_MAX_STEER < LF_BASE_SPEED)
#error "LF_MAX_STEER 必须 >= LF_BASE_SPEED: 否则慢的一侧降不到 0, 速度差上不去, 会冲过弯道"
#endif

/* ============================================================================
 *  弯道: 停车原地转向再前进
 * ----------------------------------------------------------------------------
 *  思路: 车又重又慢, 用"差速硬拐"过急弯本来就吃力(会冲出去)。
 *        不如干脆一点 —— 到弯节点【停住】, 原地把车头【转正】, 再继续前进。
 *
 *  靠什么判断"到弯节点了": 线丢了。8 路一路都看不到黑线, 说明车已经冲过了
 *  线的尽头/拐角, 这就是节点。
 *
 *  靠什么判断"转到位了": 转向过程中传感器又会扫到那条新线, 当它出现在
 *  【中间附近】(|error| <= LF_PIVOT_OK) 时, 说明车头已经对准新方向, 停转。
 *  这样不需要陀螺仪/编码器, 只用灰度就能闭环。
 * ==========================================================================*/

/* ★★ 急弯提前判定 —— 这是治"过弯冲过头"的关键 ★★
 *
 * 思路: 不用等线丢了才发现要转弯。
 *       急弯处线会先【甩到传感器最边上】(|error| 到 71 以上), 而且会持续
 *       一小会儿 —— 抓住这个信号, 立刻停车原地转向, 车头就不会冲过去。
 *
 * 为什么必须要它(实测教训):
 *   本车【传感器比车身窄】, 而且电赛 H 题那个梯形赛道 C/D 角约 104°、
 *   A/B 角约 75°, 都是急弯。
 *   原来只靠"丢线 300ms"来触发, 车在这 300ms 里已经往前冲了一大截,
 *   再转就要转更大的角度, 而且线早就滑出传感器视野了 -> 表现为
 *   "车头冲过头了, 原地旋转, 找不到线"。
 *
 * 为什么不会在直道上误触发:
 *   正常循迹时线在中间 1~2 路以内, |error| 到不了 71;
 *   只有急弯才会把线甩到边上。而且还要【持续】60ms 才算。 */
#define LF_CORNER_ERR       71      /* |error| 达到这个值 = 线已经到传感器边上了 */
#define LF_CORNER_MS        60U     /* 连续这么久满足上面的条件 -> 判定急弯, 停车转向 */

/* ★ 兜底判据: 万一线是【直接消失】的(没经历"甩到边上"), 用丢线时间兜底。
 *   150ms: 比最初的 80ms 稳(80ms 时线上一个小缺口就误触发原地转),
 *          又比 300ms 短(300ms 时过弯冲过头)。
 *   正常急弯会先被上面的 LF_CORNER_ERR 抓住, 走到这里的机会不多。 */
#define LF_PIVOT_TRIGGER_MS 150U

#define LF_PIVOT_SPEED      300     /* 原地转向时两个轮子的速度(mm/s, 一正一反)。
                                       ★ 取 300 = 和基础速度同量级:
                                         原地转向要克服的是【静摩擦】, 比滚动大得多,
                                         太小会"拧不动"、原地转向拖很久甚至超时。
                                       ★ 速度环只是"要多少给多少", 它【不会】因为
                                         静摩擦就多给 —— 真拧不动时 PI 会把占空比顶到 20,
                                         所以这里给足速度是安全的。 */
#define LF_PIVOT_OK         43      /* |error| <= 这个值就算"对准了", 结束转向。
                                       ★ 从 20 提到 43, 也就是把判据从"中间 1~2 路"
                                         放宽到"中间 4 路"。
                                       ★ 为什么必须放宽(实测反馈"车身旋转太快,
                                         巡线还没反应过来就转过去了, 然后丢线"):
                                         20 对应的窗口只有传感器阵列的约 11 度,
                                         而原地转向是【全车最快】的旋转动作
                                         (两轮一正一反, 转速约是普通转弯的 2 倍),
                                         10ms 一拍就要扫过 3 度 —— 线常常在两拍
                                         之间整段穿过去, 一次都没被抓到。
                                         结果就是"倒地转个不停, 找不到新线",
                                         最后两个方向都扫遍, 判定掉出赛道停车。
                                         放宽到 43, 窗口加倍到约 22 度, 就抓得住了。
                                       ★ 为什么现在【敢】放宽: 双环的内环收敛很快,
                                         停下时哪怕离中线还差十几度, 正常循迹也能
                                         自己掰回去 —— 单环时代不敢放宽, 是因为
                                         那时候车头掰不动。放宽还能让原地转向
                                         少转十几度, 每过一个弯省一点时间。 */
/* ★★ 原地转向的【角度界】 —— 用陀螺仪量, 不再靠计时 ★★
 *
 * 【为什么必须从"计时"改成"角度"】
 *   实车反馈: "能转回来识别到走过来的线逆行" —— 车原地转个不停, 转了大半圈
 *   之后从背后重新看到【来路】那条线, 停下来, 然后反着走回去。
 *
 *   根因是原来只有【时间】没有【角度】。一个方向最多转 LF_PIVOT_TRY_MS,
 *   而那个 1300ms 是按"原地转约 150 度/秒"估的 —— 但原地转向是两轮一正一反,
 *   差速是普通转弯的 2 倍, 实际快得多, 而且受电池电压/地面影响很大。
 *   真实速度下 1300ms 能扫将近 400 度(一整圈还多) —— 于是"扫不到线"
 *   这件事根本不会发生: 它总会扫到点什么, 包括【来路】那条线。
 *
 *   换成角度之后就与速度无关了, 能回答一个原来回答不了的问题:
 *       "已经转过 LF_PIVOT_MAX_DEG 了吗?" —— 过了就说明这个方向不对,
 *       掉头再找, 而不是继续转下去绕到来路那边去。
 *
 * ★★ 曾经还加过一个"最小角度门"(转过 40 度之前不许认线), 现在【已删除】★★
 *   出发点是不让车在刚起转那几十度里锁上【来路】。实车证明它有害:
 *     车在【直道】上也会误进原地转向(线上一个小缺口、一束杂光就够),
 *     而这时【正确的线就在原地】(yaw ≈ 0)。有了这道门, 车必须先转过 40 度
 *     才许认它 —— 可转过 40 度之后线早就出了视野, 于是车一路转到 110 度、
 *     掉头、再转到另一个 110 度、最后放弃停车。
 *     实车现象就是"直线都会掉头"。
 *   ★ 结论: 【认线不该有"至少转过多少度"的门槛】。
 *     防逆行靠 MAX 这一条就够了(见下面的推导), MIN 那条是多余且有害的。
 *
 * ★ 另一个前提: 原地转向【只在真的到弯了才该进】。直道上的短暂丢线不该
 *   触发它 —— 相关改动见 line_follow_step 丢线分支里"按证据强度给修正"那段。 */
#define LF_PIVOT_MAX_DEG    1100    /* 0.1度, 即 110 度。朝一个方向转到这个角度
                                       还没对上, 就掉头往反方向找。
                                       ★★ 它同时是一条【安全线】, 这才是它最重要的作用:
                                          来路那条线要等车头转过 180 度【再减去传感器
                                          半张角】才会重新出现在视野里 (约 158 度)。
                                          110 度加上半张角 22 度是 132 度, 离 158 度
                                          还差 26 度 —— 也就是说
                                          ★ 车头【永远转不到能看见"来路"的角度】。
                                          这才是"不会逆行"的根本保证, 而不是靠运气。
                                          (所以掉头时【不能】把 yaw 清零: 一清零,
                                           两个方向各走满 MAX, 加起来就绕到 180 度去,
                                           这条保证当场失效 —— 见代码里的说明)
                                       ★ 够不够用: 最大的弯是 105 度, 而新线在
                                         105-22 = 83 度就进窗口了, 110 度有富余。
                                         (约 132 度以上的弯会够不着 —— H 题赛道没有,
                                          换赛道要重新算。)
                                       ★ 取值依据: test/pivot_sim.mjs 把这段逻辑做了
                                         宿主仿真, 8 种组合(两个角 x 方向对/判反 x
                                         来路在前/在后)全部通过。改这个数之前先跑它。 */
#define LF_PIVOT_TRY_MS     2500U   /* ★ 现在它只是【兜底超时】。
                                       陀螺仪要是没接, yaw 恒为 0, 上面两个角度
                                       判据就永远不满足, 只能靠它掉头 + 最后停车
                                       (所以没陀螺仪时原地转向会转很久才停 ——
                                        双环本来也依赖陀螺仪, 这属于降级模式)。
                                       正常有陀螺仪时根本用不到这条。 */

/* 弯道参数的编译期检查。★ 注意必须放在这些宏【定义之后】——
 * 放在前面的话宏还没定义, 会被当成 0, 检查就没意义了(这里踩过一次)。 */
#if (LF_PIVOT_TRIGGER_MS >= LF_PIVOT_TRY_MS)
#error "LF_PIVOT_TRIGGER_MS 必须小于 LF_PIVOT_TRY_MS"
#endif
#if (LF_PIVOT_SPEED < LF_BASE_SPEED)
#error "LF_PIVOT_SPEED 不该小于 LF_BASE_SPEED: 原地转向要克服静摩擦, 得比行进时更有劲"
#endif
#if (LF_PIVOT_OK >= LF_CORNER_ERR)
#error "LF_PIVOT_OK 必须小于 LF_CORNER_ERR: 否则\"还没判定成弯\"就已经算\"对准了\", 判据自相矛盾"
#endif

/* ---------- 控制周期 ---------- */
#define LF_STEP_MS          10U     /* line_follow_step 的调用周期(ms) */

