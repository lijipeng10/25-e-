#ifndef TICK_H
#define TICK_H

#include <stdint.h>

/* ============================================================================
 *  tick.h —— 1ms 时基(基于 SysTick)
 * ----------------------------------------------------------------------------
 *  供 PID 建立时间(dt)、心跳、超时安全等使用。依赖 SysConfig 生成的
 *  CPUCLK_FREQ。用法:
 *      tick_init();        // 主循环开始前调用一次
 *      uint32_t now = tick_get_ms();
 * ==========================================================================*/

void     tick_init(void);    /* 用 SysTick 建立 1ms 中断时基 */
uint32_t tick_get_ms(void);  /* 上电以来的毫秒数(32 位, 约 49 天溢出) */

#endif /* TICK_H */
